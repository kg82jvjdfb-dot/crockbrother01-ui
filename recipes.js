const amountFormat = new Intl.NumberFormat('ru', { maximumFractionDigits: 2 });

export function scaledAmount(amount, base, servings, roundUp = false) {
  if (typeof amount === 'string') return amount;
  const quantity = base && servings ? amount * servings / base : amount;
  return amountFormat.format(roundUp ? Math.ceil(quantity) : quantity);
}
